"""Writes `reports/orders_<date>.md` and `.csv` from `order_extractions` (§8: reports are
committed to git). Reads the database rather than the in-memory `Summary` from one run, so
a report always reflects everything known for that date - including filings finished by an
earlier run or a different --follow cycle.
"""

from __future__ import annotations

import csv
from datetime import date
from pathlib import Path

from reg30_radar.common.config import ROOT

REPORTS_DIR = ROOT / "reports"
# Gitignored (`data/`), and a Docker volume on the VPS.
LIVE_REPORTS_DIR = ROOT / "data" / "reports"

ROWS_QUERY = """
select ra.symbol, ra.category_raw, oe.bucket, oe.relevance_reason, d.quality, oe.path,
       oe.consideration_raw, oe.value_inr, oe.provenance_ok, oe.company_is_recipient,
       oe.stage, oe.review_status, oe.llm_cost_usd
from order_extractions oe
join raw_announcements ra on ra.id = oe.raw_announcement_id
left join documents d on d.id = oe.document_id
where oe.order_related
  and date(ra.first_seen_at at time zone 'Asia/Kolkata') = %(day)s
order by ra.symbol
"""

TOTALS_QUERY = """
select
  count(*)                                                            as considered,
  count(*) filter (where oe.order_related)                            as order_related,
  count(*) filter (where oe.review_status = 'verified')                as verified,
  count(*) filter (where oe.review_status = 'needs_review')            as needs_review,
  count(*) filter (where oe.review_status = 'not_order')                as not_order,
  count(*) filter (where oe.review_status in ('download_failed', 'pending_llm'))
                                                                        as pending,
  count(*) filter (where oe.path = 'llm')                              as llm_calls,
  coalesce(sum(oe.llm_cost_usd), 0)                                    as llm_cost_usd,
  coalesce(sum(d.ocr_pages), 0)                                        as ocr_pages,
  count(*) filter (
    where oe.bucket = 'catch_all' and not oe.order_related
      and d.quality is not null and d.quality <> 'ok'
  )                                                                     as unreadable_catchall,
  -- The gate audit (§5.4): must always be zero. Not a filing count to review - a
  -- non-zero value here means this module's own gate was bypassed somewhere.
  count(*) filter (where oe.path = 'llm' and not oe.order_related)      as llm_gate_violations,
  count(*) filter (where d.ocr_pages > 0 and not oe.order_related)      as ocr_gate_violations
from order_extractions oe
join raw_announcements ra on ra.id = oe.raw_announcement_id
left join documents d on d.id = oe.document_id
where date(ra.first_seen_at at time zone 'Asia/Kolkata') = %(day)s
"""

ROW_COLS = ("symbol", "category_raw", "bucket", "relevance_reason", "quality", "path",
            "consideration_raw", "value_inr", "provenance_ok", "company_is_recipient",
            "stage", "review_status", "llm_cost_usd")

TOTAL_COLS = ("considered", "order_related", "verified", "needs_review", "not_order",
              "pending", "llm_calls", "llm_cost_usd", "ocr_pages", "unreadable_catchall",
              "llm_gate_violations", "ocr_gate_violations")


def fetch(conn, day: date) -> tuple[list[dict], dict]:
    rows = [dict(zip(ROW_COLS, r)) for r in conn.execute(ROWS_QUERY, {"day": day}).fetchall()]
    totals = dict(zip(TOTAL_COLS, conn.execute(TOTALS_QUERY, {"day": day}).fetchone()))
    return rows, totals


def write(conn, day: date, reports_dir: Path = REPORTS_DIR) -> tuple[str, str]:
    """Write both files for one date. Returns (md_path, csv_path) as strings.

    `reports_dir` is `reports/` (committed, §8) for a deliberate `--date`/`--from` run, and
    `LIVE_REPORTS_DIR` for `--follow`. The live worker rewrites the current day's files every
    cycle; inside the tracked `reports/` folder that left the VPS checkout permanently
    modified, and `git pull` refuses to update a file with local changes (WORKLOG, 27 Sep).
    """
    rows, totals = fetch(conn, day)
    reports_dir.mkdir(parents=True, exist_ok=True)

    md_path = reports_dir / f"orders_{day.isoformat()}.md"
    csv_path = reports_dir / f"orders_{day.isoformat()}.csv"

    md_path.write_text(_render_md(day, rows, totals), encoding="utf-8")
    with csv_path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(ROW_COLS)
        for row in rows:
            writer.writerow([row[c] for c in ROW_COLS])

    return str(md_path), str(csv_path)


def _render_md(day: date, rows: list[dict], totals: dict) -> str:
    lines = [
        f"# Order extraction report - {day.isoformat()}",
        "",
        "Generated by `python -m reg30_radar.orders` (ARCHITECTURE.md §5.4-§5.6). Only "
        "order-related filings are listed below; the full scope considered that day is "
        "in the totals.",
        "",
        "## Totals",
        "",
        f"- considered: {totals['considered']}",
        f"- order-related: {totals['order_related']}",
        f"- verified: {totals['verified']}",
        f"- needs review: {totals['needs_review']}",
        f"- not an order after all (LLM triage): {totals['not_order']}",
        f"- pending (download failed / waiting on LLM cap): {totals['pending']}",
        f"- LLM calls: {totals['llm_calls']}  (${totals['llm_cost_usd']})",
        f"- OCR pages: {totals['ocr_pages']}",
        f"- unreadable catch_all filings never escalated (accepted limitation, §5.4): "
        f"{totals['unreadable_catchall']}",
        "",
        f"**Gate audit** (must be zero): {totals['llm_gate_violations']} LLM calls and "
        f"{totals['ocr_gate_violations']} OCR pages on a filing that was not "
        f"order-related.",
        "",
        "## Order-related filings",
        "",
        "| Symbol | Category | Reason | Doc quality | Path | Value (Rs.) | Provenance | "
        "Recipient | Stage | Status | LLM cost |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['symbol'] or ''} | {r['category_raw'] or ''} | {r['relevance_reason']} "
            f"| {r['quality'] or ''} | {r['path']} | {r['value_inr'] if r['value_inr'] is not None else ''} "
            f"| {r['provenance_ok']} | {r['company_is_recipient']} | {r['stage'] or ''} "
            f"| {r['review_status']} | {r['llm_cost_usd']} |"
        )
    lines.append("")
    return "\n".join(lines)
